#!/usr/bin/env node
/**
 * Synchronizes Vite build artifacts to root HTML files and Cloudflare Worker bundle.
 */
import { readFileSync, writeFileSync, copyFileSync, statSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const distHtml = resolve(root, "dist/index.html");

if (!existsSync(distHtml)) {
  console.error("❌ dist/index.html not found. Run 'npx vite build' first.");
  process.exit(1);
}

const htmlContent = readFileSync(distHtml, "utf8");
const rawSize = statSync(distHtml).size;

// 1. Sync to root index.html and indra-ocr.html
const targetIndex = resolve(root, "index.html");
const targetOcr = resolve(root, "indra-ocr.html");

writeFileSync(targetIndex, htmlContent, "utf8");
writeFileSync(targetOcr, htmlContent, "utf8");

// 2. Generate deploy/html.js for Cloudflare Workers
const workerHtmlPath = resolve(root, "deploy/html.js");
const workerModuleContent =
  "// Auto-generated by scripts/sync-dist.mjs via Vite build\n" +
  `// Source: dist/index.html (${rawSize} bytes)\n` +
  "export default " + JSON.stringify(htmlContent) + ";\n";

writeFileSync(workerHtmlPath, workerModuleContent, "utf8");

console.log(`✓ Synchronized standalone build:`);
console.log(`  - dist/index.html    (${(rawSize / 1024).toFixed(1)} KB)`);
console.log(`  - index.html         (${(rawSize / 1024).toFixed(1)} KB)`);
console.log(`  - indra-ocr.html     (${(rawSize / 1024).toFixed(1)} KB)`);
console.log(`  - deploy/html.js     (${((statSync(workerHtmlPath).size) / 1024).toFixed(1)} KB)`);

#!/usr/bin/env node
/**
 * Automated Test & Validation Suite for INDRA OCR Web
 * Tests build artifacts, module integrity, algorithms, and isolation contracts.
 */
import { readFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

import { components } from "../src/core/detection.js";
import { xycut, decodeOrder } from "../src/core/order.js";
import { tableToMarkdown } from "../src/core/markdown.js";
import { rotateGray, orientInput } from "../src/core/index.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

let passed = 0;
let failed = 0;

function assert(condition, message) {
  if (condition) {
    console.log(`  ✓ ${message}`);
    passed++;
  } else {
    console.error(`  ✗ FAIL: ${message}`);
    failed++;
  }
}

console.log("\n🧪 Running INDRA OCR Web Engineering Test Suite\n");

// -------------------------------------------------------------
// Test Suite 1: Build Pipeline & Artifact Integrity
// -------------------------------------------------------------
console.log("📦 1. Vite Build Pipeline & Artifacts");
try {
  execSync("npx vite build && node scripts/sync-dist.mjs", { cwd: root, stdio: "pipe" });

  const distHtml = resolve(root, "dist/index.html");
  const ocrHtml = resolve(root, "indra-ocr.html");
  const indexHtml = resolve(root, "index.html");
  const workerHtml = resolve(root, "deploy/html.js");

  assert(existsSync(distHtml), "dist/index.html was generated by Vite");
  assert(existsSync(ocrHtml), "indra-ocr.html was synchronized");
  assert(existsSync(indexHtml), "index.html was synchronized");
  assert(existsSync(workerHtml), "deploy/html.js was generated");

  const ocrContent = readFileSync(ocrHtml, "utf8");
  const indexContent = readFileSync(indexHtml, "utf8");
  const distContent = readFileSync(distHtml, "utf8");

  assert(ocrContent.length > 100000 && ocrContent.length < 250000, `indra-ocr.html size is minified and healthy (${(ocrContent.length / 1024).toFixed(1)} KB)`);
  assert(indexContent.length === distContent.length, "index.html matches dist/index.html byte-for-byte");
  assert(ocrContent.length === distContent.length, "indra-ocr.html matches dist/index.html byte-for-byte");
  assert(!ocrContent.includes("/*__CORE__*/"), "No dangling /*__CORE__*/ placeholder");
  assert(!ocrContent.includes("/*__APP__*/"), "No dangling /*__APP__*/ placeholder");
  assert(ocrContent.includes("onnxruntime-web"), "ONNX Runtime Web dependency included");
  assert(ocrContent.includes("pdfjs-dist"), "pdfjs-dist dependency included");
  assert(ocrContent.includes('rel="manifest"'), "PWA manifest linked in HTML");
} catch (err) {
  assert(false, `Build script error: ${err.message}`);
}

// -------------------------------------------------------------
// Test Suite 2: Worker Edge Router & Headers Contract
// -------------------------------------------------------------
console.log("\n🌐 2. Worker Edge Router & Security Headers");
try {
  const workerSource = readFileSync(resolve(root, "deploy/worker.js"), "utf8");
  assert(workerSource.includes('"Cross-Origin-Opener-Policy": "same-origin"'), "COOP: same-origin header defined");
  assert(workerSource.includes('"Cross-Origin-Embedder-Policy": "credentialless"'), "COEP: credentialless header defined");
  assert(workerSource.includes('url.pathname === "/healthz"'), "Health check /healthz endpoint implemented");
  assert(workerSource.includes('url.pathname === "/robots.txt"'), "robots.txt SEO route implemented");
  assert(workerSource.includes('url.pathname === "/sitemap.xml"'), "sitemap.xml SEO route implemented");
  assert(workerSource.includes('url.pathname === "/manifest.webmanifest"'), "manifest route implemented");
} catch (err) {
  assert(false, `Worker source verification error: ${err.message}`);
}

// -------------------------------------------------------------
// Test Suite 3: Core Algorithm Unit Tests
// -------------------------------------------------------------
console.log("\n⚙️ 3. Core Algorithm Unit Tests");
try {
  // Test Connected Components (4-connectivity)
  const mask = new Uint8Array([
    1, 1, 0, 0,
    1, 0, 0, 0,
    0, 0, 1, 1,
    0, 0, 1, 1
  ]);
  const { stats } = components(mask, 4, 4);
  assert(stats.length === 2, `Connected components found 2 distinct blobs (got ${stats.length})`);
  assert(stats[0].area === 3, "Blob 1 has expected area 3");
  assert(stats[1].area === 4, "Blob 2 has expected area 4");

  // Test XY-cut layout algorithm
  const boxes = [
    [0, 100, 200, 150], // lower
    [0, 10, 200, 50],   // upper
  ];
  const order = xycut(boxes, [0, 1]);
  assert(order[0] === 1 && order[1] === 0, "XY-cut sorts top-down correctly");

  // Test Reading Order Pairwise Matrix Decoder
  // 3 lines: 0 before 1, 1 before 2
  const pairwise = new Float32Array([
     0,  5,  5,
    -5,  0,  5,
    -5, -5,  0
  ]);
  const decoded = decodeOrder(pairwise, 3);
  assert(decoded.join(",") === "0,1,2", `Pairwise order decode: expected [0, 1, 2], got [${decoded.join(", ")}]`);

  // Test Table Markdown Grid Reconstruction
  const sampleTableLines = [
    { box: [50, 10, 450, 25], text: "Table 1: Test Results" },
    { box: [50, 40, 150, 60], text: "Task" },
    { box: [180, 40, 280, 60], text: "Metric | Status" },
    { box: [310, 40, 410, 60], text: "Score" },
    { box: [50, 70, 150, 90], text: "OCR" },
    { box: [180, 70, 280, 90], text: "Passed" },
    { box: [310, 70, 410, 90], text: "99.8" }
  ];
  const tableMd = tableToMarkdown(sampleTableLines);
  assert(tableMd.includes("**Table 1: Test Results**"), "Table title extracted");
  assert(tableMd.includes("| Task | Metric \\| Status | Score |"), "Table header row generated and pipe escaped");
  assert(tableMd.includes("| --- | --- | --- |"), "Table divider row generated");
  assert(tableMd.includes("| OCR | Passed | 99.8 |"), "Table data row generated");

  // Test Image Orientation Deskew (rotateGray)
  // 2x3 matrix:
  // [1, 2]
  // [3, 4]
  // [5, 6]
  const gray2x3 = new Uint8Array([1, 2, 3, 4, 5, 6]);
  // Rotate 180° -> should be [6, 5, 4, 3, 2, 1]
  const rot180 = rotateGray(gray2x3, 2, 3, 2);
  assert(rot180.w === 2 && rot180.h === 3, "rotateGray 180 dimensions match");
  assert(Array.from(rot180.gray).join(",") === "6,5,4,3,2,1", "rotateGray 180 pixel order correct");

  // Rotate 90° CW -> new dims 3x2:
  // [5, 3, 1]
  // [6, 4, 2]
  const rot90 = rotateGray(gray2x3, 2, 3, 1);
  assert(rot90.w === 3 && rot90.h === 2, "rotateGray 90 dimensions match");
  assert(Array.from(rot90.gray).join(",") === "5,3,1,6,4,2", "rotateGray 90 pixel order correct");

  // Test Orient Input Preprocessor
  const orientIn = orientInput(gray2x3, 2, 3, 768);
  assert(orientIn.dims.join(",") === "1,1,768,768", "orientInput tensor dims are [1, 1, 768, 768]");
  assert(orientIn.data.length === 768 * 768, "orientInput data length is 768*768");
} catch (err) {
  assert(false, `Algorithm test error: ${err.message}`);
}

// -------------------------------------------------------------
// Summary
// -------------------------------------------------------------
console.log("\n=========================================");
console.log(`Results: ${passed} passed, ${failed} failed`);
console.log("=========================================\n");

if (failed > 0) {
  process.exit(1);
}
